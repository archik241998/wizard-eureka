from tensorflow.keras.layers import Conv2D, MaxPooling2D, Flatten

model = Sequential()
# Input layer to define the shape of the images (48x48 with 1 color channel for grayscale)
model.add(tf.keras.layers.Input(shape=(IMG_HEIGHT, IMG_WIDTH, 1))) # Changed from 3 to 1

# First Convolutional Block
model.add(Conv2D(32, kernel_size=(3, 3), activation='relu', padding='same'))
model.add(MaxPooling2D(pool_size=(2, 2)))
model.add(Dropout(0.5))

# Second Convolutional Block
model.add(Conv2D(64, kernel_size=(3, 3), activation='relu', padding='same'))
model.add(MaxPooling2D(pool_size=(2, 2)))
model.add(Dropout(0.5))

# Flatten the output before passing to Dense layers
model.add(Flatten())

# Dense layers
model.add(Dense(1024, activation='relu'))
model.add(Dropout(0.5))
model.add(Dense(7, activation='softmax')) # Output layer for 7 classes

model.summary()
model.compile(loss='categorical_crossentropy',
              optimizer='adam',
              metrics=['accuracy'])

history = model.fit(train_images, train_labels, batch_size=100, epochs = 100,   verbose=2, validation_data=(test_images, test_labels))

score = model.evaluate(test_images, test_labels, verbose=0)
print('Test loss:', score[0])
print('Test accuracy:', score[1])